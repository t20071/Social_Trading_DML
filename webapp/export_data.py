"""
Bundle the pipeline's result files into webapp/data.js for the web app.

Reads ../results/ (written by `python run_pipeline.py`) and writes data.js,
which defines `window.DML_DATA`. Uses only the Python standard library, so
any Python 3.8+ works. The web app never reads anything outside this folder.

Usage (from anywhere):
    python webapp/export_data.py                 # reads ../results next to webapp/
    python webapp/export_data.py --results PATH  # reads another results folder
"""

import argparse
import csv
import json
import math
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent


def num(value):
    """CSV cell -> float/int/None/str."""
    if value is None or value == "":
        return None
    try:
        f = float(value)
    except ValueError:
        return value
    if math.isnan(f) or math.isinf(f):
        return None
    return int(f) if f.is_integer() and "." not in value and "e" not in value.lower() else f


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return [{k: num(v) for k, v in row.items()} for row in csv.DictReader(fh)]


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def clean(obj):
    """Replace NaN/inf with None so the output is valid JSON."""
    if isinstance(obj, float):
        return None if (math.isnan(obj) or math.isinf(obj)) else obj
    if isinstance(obj, dict):
        return {k: clean(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [clean(v) for v in obj]
    return obj


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=str(HERE.parent / "results"), help="results folder to read")
    ap.add_argument("--out", default=str(HERE / "data.js"), help="output file")
    args = ap.parse_args()
    res = Path(args.results)
    if not (res / "main_results.json").exists():
        raise SystemExit(f"No results found in {res}. Run `python run_pipeline.py` first.")

    main_res = read_json(res / "main_results.json")
    het = read_json(res / "heterogeneity.json")
    data = {
        "generated": datetime.now().isoformat(timespec="seconds"),
        "manifest": read_json(res / "manifest.json") if (res / "manifest.json").exists() else None,
        "sample": main_res["sample"],
        "descriptives": main_res["descriptives"],
        "aggregates": main_res["week_aggregates"],
        "regime_break": main_res["regime_break"],
        "blocks_def": main_res["primary_spec"]["period_blocks"],
        "models": main_res["models"],
        "periods": read_csv(res / "week_decomposition.csv"),
        "blocks": read_csv(res / "week_blocks.csv"),
        "grid": read_csv(res / "robustness_grid.csv"),
        "checks": read_csv(res / "robustness_checks.csv"),
        "placebo": read_csv(res / "placebo.csv"),
        "lead": read_json(res / "lead_test.json"),
        "feedback": read_json(res / "feedback_robust.json"),
        "sensitivity": read_json(res / "sensitivity.json"),
        "forest": het["causal_forest"],
        "calibration": het["blp_calibration_heldout"],
        "gates": het["gates_heldout"],
        "block_effects": het.get("heldout_effects_by_week_block"),
        "moderators": het["blp_moderators_heldout"],
        "cohort": het.get("heldout_effects_by_join_cohort"),
    }
    payload = json.dumps(clean(data), separators=(",", ":"))
    Path(args.out).write_text(
        "// Generated by webapp/export_data.py from results/. Do not edit by hand.\n"
        f"window.DML_DATA = {payload};\n",
        encoding="utf-8",
    )
    print(f"Wrote {args.out} ({len(payload) / 1024:.0f} KB) from {res}")


if __name__ == "__main__":
    main()
